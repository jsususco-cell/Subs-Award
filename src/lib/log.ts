import "server-only";

/**
 * System Log client — vendored from byrdson-logging/clients/qb-logger.ts.
 *
 * SERVER ONLY, same as quickbase.ts: the `server-only` import above turns that
 * from a comment into a build error.
 *
 * Writes straight to the Quickbase System Log app over the REST API. Drop this in
 * the app's lib/ folder; most of our apps already hold a Quickbase user token, so
 * wiring is usually two env vars, not three:
 *
 *   QB_USER_TOKEN   already set in every app that talks to Quickbase
 *   LOG_SYSTEM      this app's System Key from the Systems table, e.g. "subs-award"
 *   LOG_COMPONENT   optional default sub-part
 *   QB_LOG_TOKEN    optional — a separate token if you do not want to reuse the above
 *
 * Without a token every function here is a no-op that still writes the line to
 * stdout, so this is safe to merge and deploy before anything else is ready.
 * Logging never throws: a failed log line must not fail the operation it describes.
 */

